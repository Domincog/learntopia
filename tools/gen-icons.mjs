#!/usr/bin/env node
/**
 * Regenerates src/ui/icons.js from the Lucide icon set (ISC licence).
 *
 *   npm install --no-save lucide-static
 *   node tools/gen-icons.mjs [path/to/lucide-static/icons]
 *
 * Only needed when you want to add an icon: add its name to ICONS below
 * ("alias:lucide-name" renames it), run the script, commit the result.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] || join(root, 'node_modules/lucide-static/icons');

const ICONS = `
home:house courses:book-open review:brain puzzle stats:chart-column profile:circle-user settings
flame zap check x lightbulb lock unlock:lock-open arrow-left arrow-right arrow-up arrow-down
chevron-right chevron-left chevron-down chevron-up play pause skip:skip-forward
volume:volume-2 mute:volume-x moon sun monitor trophy target clock star sparkles shuffle
download upload trash:trash-2 info plus minus grid:grid-3x3 code flask:flask-conical sigma
calculator shapes dice:dices binary cpu atom scatter:chart-scatter line-chart:chart-line
bars:chart-bar pie:chart-pie award medal calendar calendar-check heart eye eye-off undo:undo-2
reset:rotate-ccw help:circle-help external:external-link menu search list list-checks map compass globe
rocket sprout leaf coffee bed snowflake keyboard hand move pencil eraser flag layers timer gauge
crown gem party:party-popper footprints mountain sunrise sunset bird feather infinity pi percent
triangle circle square hexagon ruler scale branch:git-branch network bot brain-circuit workflow
variable function:square-function braces terminal bug wand:wand-sparkles message:message-circle
share:share-2 copy link check-check circle-check circle-x alert:circle-alert warning:triangle-alert
badge-check shield:shield-check offline:wifi-off phone:smartphone palette type text-size:a-large-small
contrast accessibility languages handshake:heart-handshake file:file-text folder:folder-open
repeat refresh:refresh-cw dumbbell history library school grip:grip-vertical bell telescope
microscope orbit magnet waves activity trending-up hash divide equal rabbit turtle cat squirrel
paw:paw-print tree:tree-pine moon-star glasses hourglass alarm:alarm-clock swords key
door:door-open box blocks cuboid joystick gamepad:gamepad-2 thumbs-up smile laugh quote focus
crosshair milestone route signpost waypoints pin:map-pin navigation pointer mouse-click:mouse-pointer-click
`.trim().split(/\s+/);

const out = {};
const missing = [];
for (const entry of ICONS) {
  const [alias, name = alias] = entry.split(':');
  const file = join(src, `${name}.svg`);
  if (!existsSync(file)) { missing.push(name); continue; }
  const svg = readFileSync(file, 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .replace(/ \/>/g, '/>')
    .trim();
  out[alias] = inner;
}
if (missing.length) { console.error('Missing icons:', missing.join(', ')); process.exit(1); }

const body = Object.keys(out).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join('\n');
writeFileSync(
  join(root, 'src/ui/icons.js'),
  `/**\n * Icon paths from Lucide (https://lucide.dev), ISC License.\n * GENERATED by tools/gen-icons.mjs — do not edit by hand.\n * Each value is the inner markup of a 24×24, stroke-based SVG.\n */\nexport const ICONS = {\n${body}\n};\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons to src/ui/icons.js`);
